"""Write results/SUMMARY.md: which experiments have results, where, and the command to (re)produce each one.

It only reports what exists on disk, so it can never claim a result you have not run.

    python experiments/make_summary.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from experiments.common import ROOT, md_table

# (id, title, command, files that constitute the result)
ITEMS = [
    ("P1", "Tokenizer comparison (char vs BPE, vocab vs sequence length)", "python experiments/compare_tokenizers.py", ["tokenizer_comparison.md", "tokenizer_comparison.png"]),
    ("P5", "KV-cache benchmark", "python -m src.generate --benchmark --out results/kv_cache_benchmark.md", ["kv_cache_benchmark.md"]),
    ("1", "Temperature", "python experiments/exp1_temperature.py", ["exp1_temperature.md", "exp1_temperature.png"]),
    ("2", "Prompt length / context", "python experiments/exp2_context.py", ["exp2_context.md", "exp2_loss_by_position.png"]),
    ("3", "Training dynamics", "python experiments/exp3_dynamics.py", ["exp3_dynamics.md", "exp3_dynamics.png"]),
    ("4a", "Architecture: n_layer", "python experiments/exp4_architecture.py --param n_layer", ["exp4_n_layer.md", "exp4_n_layer.png"]),
    ("4b", "Architecture: n_head", "python experiments/exp4_architecture.py --param n_head --set model.n_embd=384 --values 1 2 4 6", ["exp4_n_head.md", "exp4_n_head.png"]),
    ("4c", "Architecture: n_embd", "python experiments/exp4_architecture.py --param n_embd", ["exp4_n_embd.md", "exp4_n_embd.png"]),
    ("5", "Pre-norm vs post-norm", "python experiments/exp5_norm.py", ["exp5_norm.md", "exp5_norm.png"]),
    ("6", "Learned vs sinusoidal positions", "python experiments/exp6_pos_encoding.py", ["exp6_pos_encoding.md", "exp6_pos_encoding.png"]),
    ("7", "Char-level vs BPE (bits/char)", "python experiments/exp7_tokenizer.py", ["exp7_tokenizer.md", "exp7_tokenizer.png"]),
    ("8", "Scaling", "python experiments/exp8_scaling.py", ["exp8_scaling.md", "exp8_scaling.png"]),
    ("9", "Attention heatmaps", "python experiments/exp9_attention.py", ["exp9_attention.md", "exp9_attention_overview.png", "exp9_attention_selected.png"]),
    ("10", "Ge'ez vs English byte-BPE fragments", "python experiments/exp10_amharic.py", ["amharic/exp10_amharic.md", "amharic/exp10_amharic.png"]),
    ("11", "Amharic study (Phase 9)", "python experiments/exp11_amharic_study.py", ["amharic/tokenizer_analysis.md", "amharic/tokenizer_stats.csv", "amharic/fertility_vs_vocab.png"]),
]


def main() -> None:
    res = ROOT / "results"
    rows, done = [], 0
    for ident, title, cmd, files in ITEMS:
        present = [f for f in files if (res / f).exists()]
        status = "done" if len(present) == len(files) else ("partial" if present else "not run")
        done += status == "done"
        rows.append([ident, title, status, ", ".join(f"[{Path(f).name}]({f})" for f in present) or "-", f"`{cmd}`"])
    runs = []
    for p in sorted((ROOT / "checkpoints").glob("*/summary.json")):
        s = json.loads(p.read_text(encoding="utf-8"))
        runs.append([p.parent.name, f"{s['params']:,}", f"{s['best_val_loss']:.3f}", f"{s['val_bits_per_char']:.3f}", f"{s['train_seconds'] / 60:.1f}", s["device"]])
    text = (f"# Results summary\n\nGenerated by `experiments/make_summary.py`; {done}/{len(ITEMS)} experiments have complete results on disk.\n\n"
            + md_table(["#", "experiment", "status", "files", "command"], rows)
            + "\n\n## Trained models found in `checkpoints/`\n\n"
            + (md_table(["run", "params", "best val loss", "val bits/char", "train minutes", "device"], runs) if runs else "(none)") + "\n")
    out = res / "SUMMARY.md"
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}: {done}/{len(ITEMS)} complete")


if __name__ == "__main__":
    main()
